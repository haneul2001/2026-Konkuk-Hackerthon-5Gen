import type { EssayQuestion, MultipleQuestion, OxQuestion, QuizQuestion } from './types'

// 강의별 문제 은행(목 데이터). 요약 → 문제 생성기가 붙으면 이 파일은 지운다.
// id 규칙: {강의id}_{m|o|e}{번호}

function mc(
  id: string,
  conceptId: string,
  prompt: string,
  choices: string[],
  answerIndex: number,
  explanation: string,
): MultipleQuestion {
  return { id, conceptId, type: 'multiple', prompt, choices, answerIndex, explanation }
}

function ox(
  id: string,
  conceptId: string,
  prompt: string,
  answer: boolean,
  explanation: string,
): OxQuestion {
  return { id, conceptId, type: 'ox', prompt, answer, explanation }
}

function essay(
  id: string,
  conceptId: string,
  prompt: string,
  keywords: string[][],
  modelAnswer: string,
): EssayQuestion {
  return { id, conceptId, type: 'essay', prompt, keywords, modelAnswer, explanation: modelAnswer }
}

